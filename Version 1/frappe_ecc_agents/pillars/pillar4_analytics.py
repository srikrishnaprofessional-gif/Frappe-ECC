class FrappeNaturalLanguageQueryAgent(FrappeAIAgent):
    """Converts natural language analytical questions into parameterized Frappe QueryBuilder queries."""

    def __init__(self):
        super().__init__(
            name="frappe-natural-language-query-agent",
            pillar=AgentPillar.ANALYTICS,
            description="Translates natural language questions into secure Frappe QueryBuilder (`frappe.qb`) queries.",
            capabilities=[
                "Natural language to SQL / QueryBuilder translation",
                "SQL injection prevention via PyPika expression tree",
                "Dynamic aggregation (Sum, Count, Avg, Min, Max)",
                "Temporal range filtering (today, this_month, last_quarter)"
            ],
            system_prompt="You convert conversational questions into pure Frappe QueryBuilder Python expressions."
        )

    def execute(self, context: AgentContext, result: AgentResult) -> None:
        target_doctype = f"{context.app_title} Record"
        nlq_code = f"""# Generated by FrappeNaturalLanguageQueryAgent
import frappe
from frappe.query_builder import DocType
from frappe.query_builder.functions import Sum, Count

@frappe.whitelist()
def run_natural_query(query_text="Show total amount by status"):
    \"\"\"Converts query text into Frappe QueryBuilder execution.\"\"\"
    Record = DocType("{target_doctype}")
    
    query = (
        frappe.qb.from_(Record)
        .select(Record.status, Count(Record.name).as_("count"), Sum(Record.requested_amount).as_("total_amount"))
        .groupby(Record.status)
    )
    
    return query.run(as_dict=True)
"""
        result.summary = "Constructed Natural Language Query (NLQ) engine with Frappe QueryBuilder."
        result.artifacts["nlq_engine"] = nlq_code
        result.add_deliverable(
            title="NLQ Query Engine",
            file_path=f"{context.project_name}/services/nlq_service.py",
            content=nlq_code,
            file_type="python"
        )


