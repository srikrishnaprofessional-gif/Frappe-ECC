class FrappeReportBuilderAgent(FrappeAIAgent):
    """Generates server-side Script Reports, Query Reports, and exportable financial summaries."""

    def __init__(self):
        super().__init__(
            name="frappe-report-builder",
            pillar=AgentPillar.ANALYTICS,
            description="Constructs Frappe Script Reports with dynamic Python query logic, filters, and client JS formatters.",
            capabilities=[
                "Script Report Python execution logic",
                "Report column definitions and formatting",
                "Client-side JS filter declarations",
                "Chart integration within reports"
            ],
            system_prompt="You build high-performance Frappe Script Reports and Query Reports."
        )

    def execute(self, context: AgentContext, result: AgentResult) -> None:
        slug = context.project_name
        report_py = f"""# Script Report: {context.app_title} Summary
import frappe

def execute(filters=None):
    columns = [
        {{"label": "ID", "fieldname": "name", "fieldtype": "Link", "options": "{context.app_title} Record", "width": 140}},
        {{"label": "Applicant", "fieldname": "applicant_name", "fieldtype": "Data", "width": 180}},
        {{"label": "Status", "fieldname": "status", "fieldtype": "Data", "width": 120}},
        {{"label": "Amount", "fieldname": "requested_amount", "fieldtype": "Currency", "width": 140}},
        {{"label": "Date", "fieldname": "creation", "fieldtype": "Date", "width": 120}}
    ]
    
    conditions = {{}}
    if filters and filters.get("status"):
        conditions["status"] = filters.get("status")
        
    data = frappe.get_all(
        "{context.app_title} Record",
        filters=conditions,
        fields=["name", "applicant_name", "status", "requested_amount", "creation"]
    )
    
    return columns, data
"""
        report_js = f"""// Script Report Filters: {context.app_title} Summary
frappe.query_reports["{context.app_title} Summary"] = {{
    "filters": [
        {{
            "fieldname": "status",
            "label": __("Status"),
            "fieldtype": "Select",
            "options": "\\nDraft\\nUnder Review\\nApproved\\nRejected"
        }}
    ]
}};
"""
        result.summary = f"Created Script Report backend and filter frontend for '{context.app_title} Summary'."
        result.artifacts["report_py"] = report_py
        result.artifacts["report_js"] = report_js
        result.add_deliverable(
            title="Script Report Controller",
            file_path=f"{slug}/{slug}/report/{slug}_summary/{slug}_summary.py",
            content=report_py,
            file_type="python"
        )
        result.add_deliverable(
            title="Script Report Client JS",
            file_path=f"{slug}/{slug}/report/{slug}_summary/{slug}_summary.js",
            content=report_js,
            file_type="javascript"
        )
